using Bazaar.Server.BrowserPool.LinuxHost;

namespace Bazaar.Server.BrowserPool.Image.Tests;

public class ScriptTests
{
    private static string Render(PoolImageOptions? image = null, BrowserPoolOptions? pool = null, LinuxPoolHostOptions? host = null) =>
        PoolImageScript.Render(image ?? new PoolImageOptions(), pool ?? new BrowserPoolOptions(), host ?? new LinuxPoolHostOptions());

    [Fact]
    public void Default_script_is_as_designed()
    {
        string expected =
            "#!/bin/sh\n"
            + "# Provisions an Ubuntu 24.04 browser pool VM. Generated by Bazaar.Server.BrowserPool.Image; run once as root.\n"
            + "set -eu\n\n"
            + "export DEBIAN_FRONTEND=noninteractive\n"
            + "apt-get update\n"
            + "apt-get install -y --no-install-recommends chromium bubblewrap util-linux procps nftables iproute2 cage apparmor\n\n"
            + "# Lets bwrap, and only bwrap, create user namespaces.\n"
            + "cat > /etc/apparmor.d/bazaar-pool-bwrap <<'BAZAAR_POOL_BWRAP_PROFILE'\n"
            + BwrapAppArmorProfile.Render("/usr/bin/bwrap")
            + "BAZAAR_POOL_BWRAP_PROFILE\n"
            + "chmod 0644 /etc/apparmor.d/bazaar-pool-bwrap\n"
            + "apparmor_parser -r /etc/apparmor.d/bazaar-pool-bwrap\n\n"
            + "# Slot root: root-owned, slots may only traverse it.\n"
            + "mkdir -p /var/lib/bazaar-pool\n"
            + "chown root:root /var/lib/bazaar-pool\n"
            + "chmod 0711 /var/lib/bazaar-pool\n";

        Assert.Equal(expected, Render());
    }

    [Fact]
    public void The_pipe_parent_is_created_when_the_helper_is_set()
    {
        string script = Render(host: new LinuxPoolHostOptions { PoolSpawnHelperPath = "/opt/bazaar/bazaar-pool-spawn" });

        Assert.Contains("mkdir -p /run/bazaar-pool\nchown root:root /run/bazaar-pool\nchmod 0700 /run/bazaar-pool\n", script);
    }

    [Fact]
    public void The_pipe_parent_is_recreated_at_boot_when_the_helper_is_set()
    {
        string script = Render(host: new LinuxPoolHostOptions { PoolSpawnHelperPath = "/opt/bazaar/bazaar-pool-spawn" });

        Assert.Contains("printf 'd %s 0700 root root -\\n' /run/bazaar-pool > /etc/tmpfiles.d/bazaar-pool.conf\nchmod 0644 /etc/tmpfiles.d/bazaar-pool.conf\n", script);
        Assert.DoesNotContain("tmpfiles.d", Render());
    }

    [Fact]
    public void No_pipe_parent_without_the_helper()
    {
        Assert.DoesNotContain("/run/bazaar-pool", Render());
    }

    [Fact]
    public void Rendering_twice_gives_the_same_text()
    {
        Assert.Equal(Render(), Render());
    }

    [Fact]
    public void Uses_strict_shell_mode_and_a_quoted_heredoc()
    {
        string script = Render();

        Assert.StartsWith("#!/bin/sh\n", script);
        Assert.Contains("\nset -eu\n", script);
        Assert.Contains("<<'BAZAAR_POOL_BWRAP_PROFILE'", script);
        Assert.Contains("\napparmor_parser -r ", script);
    }

    [Fact]
    public void Never_weakens_the_sandbox_or_fetches_from_the_network()
    {
        string script = Render(host: new LinuxPoolHostOptions { PoolSpawnHelperPath = "/opt/bazaar/bazaar-pool-spawn" });

        foreach (var forbidden in new[] { "--no-sandbox", "apparmor_restrict_unprivileged_userns", "sysctl", "unprivileged_userns_clone", "curl", "wget", "http://", "https://", "chmod 777", "chmod -R" })
        {
            Assert.DoesNotContain(forbidden, script);
        }
    }

    [Fact]
    public void Duplicate_packages_are_installed_once()
    {
        string script = Render(new PoolImageOptions { Packages = ["cage", "cage", "apparmor"] });

        Assert.Contains("--no-install-recommends cage apparmor\n", script);
    }

    [Theory]
    [InlineData("chromium; rm -rf /")]
    [InlineData("a b")]
    [InlineData("$(id)")]
    [InlineData("Chromium")]
    [InlineData("-y")]
    [InlineData("x")]
    [InlineData("")]
    [InlineData("pkg\nrm")]
    public void An_unsafe_package_name_throws(string name)
    {
        Assert.Throws<ArgumentException>(() => Render(new PoolImageOptions { Packages = ["cage", name] }));
    }

    [Fact]
    public void An_empty_package_list_throws()
    {
        Assert.Throws<ArgumentException>(() => Render(new PoolImageOptions { Packages = [] }));
    }

    [Fact]
    public void An_unsafe_slot_root_or_bwrap_path_throws()
    {
        Assert.Throws<ArgumentException>(() => Render(pool: new BrowserPoolOptions { SlotRoot = "/var/lib/x; rm -rf /" }));
        Assert.Throws<ArgumentException>(() => Render(pool: new BrowserPoolOptions { BwrapPath = "/usr/bin/bwrap\nEOF" }));
    }

    [Fact]
    public void The_configured_bwrap_and_slot_paths_are_used()
    {
        string script = Render(pool: new BrowserPoolOptions { BwrapPath = "/opt/b/bwrap", SlotRoot = "/srv2/slots" });

        Assert.Contains("profile bazaar-pool-bwrap /opt/b/bwrap flags=(unconfined)", script);
        Assert.Contains("chmod 0711 /srv2/slots\n", script);
    }
}
