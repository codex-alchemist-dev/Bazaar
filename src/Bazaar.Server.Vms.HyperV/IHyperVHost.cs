using Bazaar.Server.Vms.Environments;
using Bazaar.Server.Vms.Lifecycle;

namespace Bazaar.Server.Vms.HyperV;

/// <summary>What Hyper-V reports for one VM, reduced to the states the backend acts on.</summary>
public enum HyperVVmState
{
    /// <summary>No VM of that name exists.</summary>
    Missing,

    /// <summary>Powered off.</summary>
    Off,

    Running,

    /// <summary>Paused in memory. The backend treats it as running: it holds memory and can be saved or turned off.</summary>
    Paused,

    /// <summary>Memory and device state are on disk and the VM is not running.</summary>
    Saved,

    /// <summary>Starting, saving, stopping or another transition. The caller retries after it settles.</summary>
    Transitioning,
}

/// <summary>A new VM: a name the backend generated, the guest OS, its sizing, and the child disk it boots from.</summary>
public sealed record HyperVVmDefinition(string Name, VmOs Os, int Vcpu, int MemoryMb, string DiskPath);

/// <summary>
/// The only seam to Hyper-V. Every call that touches the host goes through here, so the backend is tested with a fake and cloud CI
/// never needs the role. Names are generated by the backend (<see cref="HyperVNames"/>); an adapter must refuse any other name.
/// </summary>
public interface IHyperVHost
{
    /// <summary>Creates a differencing disk for a VM off <paramref name="parentDiskPath"/> and returns the child disk's path.</summary>
    Task<string> CreateDifferencingDiskAsync(string vmName, string parentDiskPath, CancellationToken ct);

    /// <summary>Creates a generation 2 VM with static memory, no network connection and no automatic checkpoints.</summary>
    Task CreateVmAsync(HyperVVmDefinition vm, CancellationToken ct);

    Task StartAsync(string vmName, CancellationToken ct);

    /// <summary>A graceful stop asks the guest to shut down; a forced stop is a power cut.</summary>
    Task StopAsync(string vmName, bool force, CancellationToken ct);

    /// <summary>Saves memory and device state to disk and stops the VM.</summary>
    Task SaveAsync(string vmName, CancellationToken ct);

    Task CheckpointAsync(string vmName, string checkpointName, CancellationToken ct);

    Task RestoreAsync(string vmName, string checkpointName, CancellationToken ct);

    /// <summary>Removes the VM and its checkpoints, and its disk when <paramref name="deleteDisk"/> is set. Removing a missing VM succeeds.</summary>
    Task RemoveAsync(string vmName, bool deleteDisk, CancellationToken ct);

    Task<HyperVVmState> GetStateAsync(string vmName, CancellationToken ct);
}

/// <summary>Where the golden image a child is created from lives on this host.</summary>
public interface IHyperVParentResolver
{
    /// <summary>The path of the parent VHDX for an image version. Throws when the version is not on this host.</summary>
    string ResolveParentDisk(ImageVersionId parent);
}

/// <summary>Resolves a parent to <c>&lt;directory&gt;/&lt;version id&gt;.vhdx</c>, the layout the image builder writes on a Hyper-V host.</summary>
public sealed class DirectoryParentResolver(string imageDirectory) : IHyperVParentResolver
{
    /// <inheritdoc />
    public string ResolveParentDisk(ImageVersionId parent) =>
        Path.Combine(imageDirectory, parent.Value.ToString("N") + ".vhdx");
}
