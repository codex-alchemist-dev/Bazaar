using Bazaar.Server.Vms.Environments;
using Bazaar.Server.Vms.Lifecycle;

namespace Bazaar.Server.Vms.Kvm;

/// <summary>What libvirt reports for one domain, reduced to the states the backend acts on.</summary>
public enum KvmDomainState
{
    /// <summary>No domain of that name is defined.</summary>
    Missing,

    /// <summary>Defined and shut off, with no managed save image.</summary>
    Off,

    Running,

    /// <summary>Paused in memory. The backend treats it as running: it holds memory and can be saved or destroyed.</summary>
    Paused,

    /// <summary>Shut off with a managed save image on disk: memory and device state are saved and the next start resumes them.</summary>
    Saved,

    /// <summary>Shutting down, crashed or another transition. The caller retries after it settles.</summary>
    Transitioning,
}

/// <summary>A new domain: a name the backend generated, the guest OS, its sizing, and the child disk it boots from.</summary>
public sealed record KvmDomainDefinition(string Name, VmOs Os, int Vcpu, int MemoryMb, string DiskPath);

/// <summary>
/// The only seam to libvirt and qemu-img. Every call that touches the host goes through here, so the backend is tested with a fake
/// and cloud CI never needs KVM. Names are generated by the backend (<see cref="KvmNames"/>); an adapter must refuse any other name.
/// </summary>
public interface IKvmHost
{
    /// <summary>Creates a qcow2 child disk for a domain with <paramref name="parentDiskPath"/> as its read-only backing file and returns the child's path.</summary>
    Task<string> CreateBackedDiskAsync(string domainName, string parentDiskPath, CancellationToken ct);

    /// <summary>Defines a domain with a virtio vsock device, static memory, no network interface and no graphics beyond what the VM spec allows.</summary>
    Task DefineAsync(KvmDomainDefinition domain, CancellationToken ct);

    Task StartAsync(string domainName, CancellationToken ct);

    /// <summary>A graceful stop asks the guest to shut down and waits for it; a forced stop is a power cut (destroy).</summary>
    Task StopAsync(string domainName, bool force, CancellationToken ct);

    /// <summary>Saves memory and device state to disk and stops the domain (managed save).</summary>
    Task SaveAsync(string domainName, CancellationToken ct);

    /// <summary>Takes an internal snapshot of a shut-off domain.</summary>
    Task CheckpointAsync(string domainName, string checkpointName, CancellationToken ct);

    Task RestoreAsync(string domainName, string checkpointName, CancellationToken ct);

    /// <summary>Undefines the domain with its snapshots and managed save image, and deletes its disk when <paramref name="deleteDisk"/> is set. Removing a missing domain succeeds.</summary>
    Task RemoveAsync(string domainName, bool deleteDisk, CancellationToken ct);

    Task<KvmDomainState> GetStateAsync(string domainName, CancellationToken ct);
}

/// <summary>Where the golden image a child is created from lives on this host.</summary>
public interface IKvmParentResolver
{
    /// <summary>The path of the parent qcow2 for an image version. Throws when the version is not on this host.</summary>
    string ResolveParentDisk(ImageVersionId parent);
}

/// <summary>Resolves a parent to <c>&lt;directory&gt;/&lt;version id&gt;.qcow2</c>, the layout the image builder writes on a KVM host.</summary>
public sealed class DirectoryParentResolver(string imageDirectory) : IKvmParentResolver
{
    /// <inheritdoc />
    public string ResolveParentDisk(ImageVersionId parent) =>
        Path.Combine(imageDirectory, parent.Value.ToString("N") + ".qcow2");
}
