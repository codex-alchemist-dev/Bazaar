using System.Text;
using Bazaar.Server.BrowserPool.LinuxHost;

namespace Bazaar.Server.BrowserPool.Image;

/// <summary>
/// Renders the POSIX <c>sh</c> script that provisions an Ubuntu 24.04 pool VM (docs/design/59, section 11). The same options always
/// give the same text. Every interpolated value is checked first (package names against a strict pattern, paths against the safe path
/// check), the AppArmor profile goes in through a quoted heredoc, and the script never turns off Chromium's sandbox or the system's
/// user namespace restriction. The only network use is the package manager.
/// </summary>
public static class PoolImageScript
{
    private const string HeredocTag = "BAZAAR_POOL_BWRAP_PROFILE";

    /// <summary>Renders the script.</summary>
    /// <exception cref="ArgumentException">A package name or a path is not acceptable.</exception>
    public static string Render(PoolImageOptions image, BrowserPoolOptions pool, LinuxPoolHostOptions host)
    {
        ArgumentNullException.ThrowIfNull(image);
        ArgumentNullException.ThrowIfNull(pool);
        ArgumentNullException.ThrowIfNull(host);

        var packages = new List<string>();
        foreach (var name in image.Packages ?? throw new ArgumentException("No package list.", nameof(image)))
        {
            if (!PoolImageOptions.IsValidPackageName(name))
            {
                throw new ArgumentException("A package name is not acceptable.", nameof(image));
            }

            if (!packages.Contains(name))
            {
                packages.Add(name);
            }
        }

        if (packages.Count == 0)
        {
            throw new ArgumentException("The package list is empty.", nameof(image));
        }

        if (!BrowserPoolOptionsValidator.IsSafeAbsolutePath(pool.SlotRoot))
        {
            throw new ArgumentException("The slot root is not a safe absolute path.", nameof(pool));
        }

        string profile = BwrapAppArmorProfile.Render(pool.BwrapPath);

        var sb = new StringBuilder();
        sb.Append("#!/bin/sh\n");
        sb.Append("# Provisions an Ubuntu 24.04 browser pool VM. Generated by Bazaar.Server.BrowserPool.Image; run once as root.\n");
        sb.Append("set -eu\n\n");
        sb.Append("export DEBIAN_FRONTEND=noninteractive\n");
        sb.Append("apt-get update\n");
        sb.Append("apt-get install -y --no-install-recommends");
        foreach (var name in packages)
        {
            sb.Append(' ').Append(name);
        }

        sb.Append("\n\n");
        sb.Append("# Lets bwrap, and only bwrap, create user namespaces.\n");
        sb.Append("cat > ").Append(BwrapAppArmorProfile.InstallPath).Append(" <<'").Append(HeredocTag).Append("'\n");
        sb.Append(profile);
        sb.Append(HeredocTag).Append('\n');
        sb.Append("chmod 0644 ").Append(BwrapAppArmorProfile.InstallPath).Append('\n');
        sb.Append("apparmor_parser -r ").Append(BwrapAppArmorProfile.InstallPath).Append("\n\n");

        sb.Append("# Slot root: root-owned, slots may only traverse it.\n");
        AppendDirectory(sb, pool.SlotRoot, "0711");

        if (host.PoolSpawnHelperPath is not null)
        {
            string parent = PoolImageRequirements.PipeParent(host);
            sb.Append("\n# Parent of the DevTools pipe directory: root only.\n");
            AppendDirectory(sb, parent, "0700");
        }

        return sb.ToString();
    }

    private static void AppendDirectory(StringBuilder sb, string path, string mode)
    {
        sb.Append("mkdir -p ").Append(path).Append('\n');
        sb.Append("chown root:root ").Append(path).Append('\n');
        sb.Append("chmod ").Append(mode).Append(' ').Append(path).Append('\n');
    }
}
