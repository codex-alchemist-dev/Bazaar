using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Bazaar.Wire.Generators;

/// <summary>
/// Emits the MemoryPack registry and direct <c>MemoryPackWriter</c>/<c>MemoryPackReader</c> code for every payload (doc 90
/// sections 3 and 3.2). MemoryPack's own source generator cannot be used: a Roslyn generator never sees another generator's
/// output, so mirror DTOs emitted here would never get their <c>[MemoryPackable]</c> code. This emitter writes the formatters
/// itself, in MemoryPack's version-tolerant object layout (member count, one varint length per member, member bytes), over the
/// public reader and writer, so the decode limits are checked inline while reading and Contracts needs no MemoryPack reference.
/// </summary>
internal static class MemoryPackEmitter
{
    /// <summary>The most members a MemoryPack object header can announce (the byte value 255 means null).</summary>
    internal const int MaxMembers = 249;

    public static string Emit(Compilation compilation, List<PayloadInfo> payloads, List<DiagnosticInfo> diagnostics, System.Threading.CancellationToken ct)
    {
        var context = new EmitContext(diagnostics, ct);
        foreach (var payload in payloads)
        {
            var reference = context.Resolve(payload.Type, NullableAnnotation.NotAnnotated);
            if (reference is not null) context.IdOf(reference);
        }

        context.Drain();

        var ns = compilation.AssemblyName is { Length: > 0 } name ? name + ".Generated" : "Generated";
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by Bazaar.Wire.Generators from the [WirePayload] records in Bazaar.Contracts. Do not edit.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine("using MemoryPackReader = global::MemoryPack.MemoryPackReader;");
        sb.AppendLine("using Limits = global::Bazaar.Wire.Codec.MemoryPack.MemoryPackLimits;");
        sb.AppendLine("using Rt = global::Bazaar.Wire.Codec.MemoryPack.MemoryPackWireRuntime;");
        sb.AppendLine();
        sb.Append("namespace ").Append(ns).AppendLine(";");
        sb.AppendLine();
        sb.AppendLine("/// <summary>The closed set of wire payload types and their MemoryPack readers and writers.</summary>");
        sb.AppendLine("internal static partial class WireMemoryPackPayloads");
        sb.AppendLine("{");

        sb.AppendLine("    /// <summary>Every registered payload type with the message types it travels under (empty for replies and shared shapes).</summary>");
        sb.AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<(global::System.Type Type, global::System.Collections.Generic.IReadOnlyList<string> MessageTypes)> All { get; } =");
        sb.AppendLine("    [");
        foreach (var payload in payloads)
        {
            var types = string.Join(", ", payload.MessageTypes.Select(t => "\"" + CborEmitter.Escape(t) + "\""));
            sb.Append("        (typeof(").Append(CborEmitter.Fq(payload.Type)).Append("), new string[] { ").Append(types).AppendLine(" }),");
        }

        sb.AppendLine("    ];");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>True when <typeparamref name=\"T\"/> is a registered wire payload.</summary>");
        sb.AppendLine("    public static bool IsRegistered<T>()");
        sb.AppendLine("    {");
        sb.Append("        return ");
        sb.Append(payloads.Count == 0 ? "false" : string.Join("\n            || ", payloads.Select(p => $"typeof(T) == typeof({CborEmitter.Fq(p.Type)})")));
        sb.AppendLine(";");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>Writes one payload as one MemoryPack object.</summary>");
        sb.AppendLine("    public static void Write<T, TW>(ref global::MemoryPack.MemoryPackWriter<TW> w, T value) where TW : class, global::System.Buffers.IBufferWriter<byte>");
        sb.AppendLine("    {");
        foreach (var payload in payloads)
        {
            var id = context.IdOf(new TypeRef(payload.Type, false, WireKind.Record, null));
            sb.AppendLine($"        if (typeof(T) == typeof({CborEmitter.Fq(payload.Type)})) {{ W{id}(ref w, ({CborEmitter.Fq(payload.Type)})(object)value!); return; }}");
        }

        sb.AppendLine("        throw new global::System.NotSupportedException(typeof(T).Name + \" is not a registered wire payload.\");");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>Reads one payload object, enforcing the decode limits. The payload sits one level inside the envelope.</summary>");
        sb.AppendLine("    public static T Read<T>(ref MemoryPackReader r, Limits l)");
        sb.AppendLine("    {");
        foreach (var payload in payloads)
        {
            var id = context.IdOf(new TypeRef(payload.Type, false, WireKind.Record, null));
            sb.AppendLine($"        if (typeof(T) == typeof({CborEmitter.Fq(payload.Type)})) return (T)(object)R{id}(ref r, l, 2)!;");
        }

        sb.AppendLine("        throw new global::System.NotSupportedException(typeof(T).Name + \" is not a registered wire payload.\");");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.Append(context.Methods);
        sb.AppendLine("}");
        return sb.ToString();
    }

    internal const string WriterGeneric = "<TW>";
    internal const string WriterConstraint = " where TW : class, global::System.Buffers.IBufferWriter<byte>";

    private sealed class EmitContext
    {
        private readonly List<DiagnosticInfo> _diagnostics;
        private readonly TypeResolver _resolver;
        private readonly System.Threading.CancellationToken _ct;
        private readonly Dictionary<string, int> _ids = new(StringComparer.Ordinal);
        private readonly Queue<(int Id, TypeRef Type)> _queue = new();

        public EmitContext(List<DiagnosticInfo> diagnostics, System.Threading.CancellationToken ct)
        {
            _diagnostics = diagnostics;
            _resolver = new TypeResolver(diagnostics);
            _ct = ct;
        }

        public StringBuilder Methods { get; } = new();

        public TypeRef? Resolve(ITypeSymbol symbol, NullableAnnotation annotation) => _resolver.Resolve(symbol, annotation);

        public int IdOf(TypeRef type)
        {
            var key = type.Display();
            if (_ids.TryGetValue(key, out var id)) return id;
            id = _ids.Count;
            _ids[key] = id;
            _queue.Enqueue((id, type));
            return id;
        }

        public void Drain()
        {
            while (_queue.Count > 0)
            {
                _ct.ThrowIfCancellationRequested();
                var (id, type) = _queue.Dequeue();
                EmitMethods(id, type);
            }
        }

        private void WriterSignature(int id, string display) =>
            Methods.AppendLine($"    private static void W{id}{WriterGeneric}(ref global::MemoryPack.MemoryPackWriter{WriterGeneric} w, {display} v){WriterConstraint}");

        private void ReaderSignature(int id, string display) =>
            Methods.AppendLine($"    private static {display} R{id}(ref MemoryPackReader r, Limits l, int depth)");

        private void Simple(int id, string display, string write, string read)
        {
            WriterSignature(id, display);
            Methods.AppendLine($"    {{ {write} }}");
            ReaderSignature(id, display);
            Methods.AppendLine($"        => {read};");
            Methods.AppendLine();
        }

        private void EmitMethods(int id, TypeRef type)
        {
            var display = type.Display();
            Methods.AppendLine($"    // {display}");
            if (type.Nullable && type.Symbol.IsValueType)
            {
                // A nullable value type (only reachable as a collection element; a member that is null is left out of its object): flag byte, then the value.
                var inner = IdOf(type.NonNull);
                WriterSignature(id, display);
                Methods.AppendLine("    {");
                Methods.AppendLine("        if (!v.HasValue) { w.WriteUnmanaged((byte)0); return; }");
                Methods.AppendLine("        w.WriteUnmanaged((byte)1);");
                Methods.AppendLine($"        W{inner}(ref w, v.Value);");
                Methods.AppendLine("    }");
                ReaderSignature(id, display);
                Methods.AppendLine("    {");
                Methods.AppendLine("        if (!Rt.ReadFlag(ref r)) return default;");
                Methods.AppendLine($"        return R{inner}(ref r, l, depth);");
                Methods.AppendLine("    }");
                Methods.AppendLine();
                return;
            }

            var nullable = type.Nullable ? "true" : "false";
            switch (type.Kind)
            {
                case WireKind.String:
                    Simple(id, display, "w.WriteString(v);", $"Rt.ReadString(ref r, l, {nullable})");
                    break;
                case WireKind.Bool:
                    Simple(id, display, "w.WriteUnmanaged((byte)(v ? 1 : 0));", "Rt.ReadBool(ref r)");
                    break;
                case WireKind.Byte:
                    Simple(id, display, "w.WriteUnmanaged(v);", "r.ReadUnmanaged<byte>()");
                    break;
                case WireKind.Int32:
                    Simple(id, display, "w.WriteUnmanaged(v);", "r.ReadUnmanaged<int>()");
                    break;
                case WireKind.Int64:
                    Simple(id, display, "w.WriteUnmanaged(v);", "r.ReadUnmanaged<long>()");
                    break;
                case WireKind.Single:
                    Simple(id, display, "w.WriteUnmanaged(v);", "r.ReadUnmanaged<float>()");
                    break;
                case WireKind.Double:
                    Simple(id, display, "w.WriteUnmanaged(v);", "r.ReadUnmanaged<double>()");
                    break;
                case WireKind.Decimal:
                    Simple(id, display, "Rt.WriteDecimal(ref w, v);", "Rt.ReadDecimal(ref r)");
                    break;
                case WireKind.Guid:
                    Simple(id, display, "w.WriteUnmanaged(v);", "r.ReadUnmanaged<global::System.Guid>()");
                    break;
                case WireKind.DateTimeOffset:
                    Simple(id, display, "Rt.WriteDateTimeOffset(ref w, v);", "Rt.ReadDateTimeOffset(ref r)");
                    break;
                case WireKind.Float32Array:
                    Simple(id, display, "w.WriteUnmanagedArray(v);", $"Rt.ReadFloat32Array(ref r, l, {nullable})");
                    break;
                case WireKind.Float32Memory:
                    Simple(id, display, "w.WriteUnmanagedSpan(v.Span);", "new global::System.ReadOnlyMemory<float>(Rt.ReadFloat32Array(ref r, l, false))");
                    break;
                case WireKind.Enum:
                    EmitEnum(id, display, (INamedTypeSymbol)type.Symbol);
                    break;
                case WireKind.ReadOnlyList:
                case WireKind.List:
                case WireKind.Array:
                    EmitList(id, display, type);
                    break;
                case WireKind.Record:
                    EmitRecord(id, display, type);
                    break;
            }
        }

        private void EmitEnum(int id, string display, INamedTypeSymbol symbol)
        {
            var underlying = CborEmitter.Fq(symbol.EnumUnderlyingType!);
            var values = new List<string>();
            string? fallback = null;
            foreach (var field in symbol.GetMembers().OfType<IFieldSymbol>())
            {
                if (!field.IsConst) continue;
                values.Add(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatPrimitive(field.ConstantValue!, false, false));
                if (field.Name == "Unknown" || (field.Name == "Unspecified" && fallback is null)) fallback = field.Name;
            }

            WriterSignature(id, display);
            Methods.AppendLine("    {");
            Methods.AppendLine($"        w.WriteUnmanaged(({underlying})v);");
            Methods.AppendLine("    }");
            ReaderSignature(id, display);
            Methods.AppendLine("    {");
            Methods.AppendLine($"        var x = r.ReadUnmanaged<{underlying}>();");
            Methods.AppendLine("        switch (x)");
            Methods.AppendLine("        {");
            foreach (var value in values.Distinct(StringComparer.Ordinal)) Methods.AppendLine($"            case {value}:");
            Methods.AppendLine($"                return ({display})x;");
            Methods.AppendLine(fallback is null
                ? $"            default: throw Rt.UnknownEnum(\"{symbol.Name}\", x.ToString());"
                : $"            default: return {display}.{fallback};");
            Methods.AppendLine("        }");
            Methods.AppendLine("    }");
            Methods.AppendLine();
        }

        private void EmitList(int id, string display, TypeRef type)
        {
            var element = type.Element!;
            var elementId = IdOf(element);
            var elementDisplay = element.Display();
            var count = type.Kind == WireKind.Array ? "Length" : "Count";
            WriterSignature(id, display);
            Methods.AppendLine("    {");
            Methods.AppendLine($"        w.WriteCollectionHeader(v.{count});");
            Methods.AppendLine($"        for (var i = 0; i < v.{count}; i++) W{elementId}(ref w, v[i]);");
            Methods.AppendLine("    }");
            ReaderSignature(id, display);
            Methods.AppendLine("    {");
            Methods.AppendLine($"        if (!Rt.ReadCollectionStart(ref r, l, depth, {(type.Nullable ? "true" : "false")}, out var n)) return default;");
            if (type.Kind == WireKind.Array)
            {
                Methods.AppendLine($"        var items = new {elementDisplay}[n];");
                Methods.AppendLine($"        for (var i = 0; i < n; i++) items[i] = R{elementId}(ref r, l, depth + 1);");
            }
            else
            {
                Methods.AppendLine($"        var items = new global::System.Collections.Generic.List<{elementDisplay}>(n);");
                Methods.AppendLine($"        for (var i = 0; i < n; i++) items.Add(R{elementId}(ref r, l, depth + 1));");
            }

            Methods.AppendLine("        return items;");
            Methods.AppendLine("    }");
            Methods.AppendLine();
        }

        private void EmitRecord(int id, string display, TypeRef type)
        {
            var symbol = (INamedTypeSymbol)type.Symbol;
            if (RecordShape.Analyze(symbol, _resolver, _diagnostics) is not { } shape) return;
            var fields = shape.Fields;
            var constructor = shape.Constructor;
            if (fields.Count > MaxMembers)
            {
                _diagnostics.Add(new DiagnosticInfo(Descriptors.TooManyFields, symbol.ToDisplayString()));
                return;
            }

            for (var i = 0; i < fields.Count; i++) fields[i].Local = "f" + i.ToString(CultureInfo.InvariantCulture);
            var isStruct = symbol.IsValueType;

            WriterSignature(id, display);
            Methods.AppendLine("    {");
            if (!isStruct && type.Nullable)
            {
                Methods.AppendLine("        if (v is null) { w.WriteNullObjectHeader(); return; }");
            }

            Methods.AppendLine("        var tmp = global::MemoryPack.Internal.ReusableLinkedArrayBufferWriterPool.Rent();");
            Methods.AppendLine("        try");
            Methods.AppendLine("        {");
            Methods.AppendLine($"            global::System.Span<int> offsets = stackalloc int[{Math.Max(fields.Count, 1)}];");
            Methods.AppendLine("            var tw = new global::MemoryPack.MemoryPackWriter<global::MemoryPack.Internal.ReusableLinkedArrayBufferWriter>(ref tmp, w.OptionalState);");
            for (var i = 0; i < fields.Count; i++)
            {
                var f = fields[i];
                var propertyId = IdOf(f.WriteType.NonNull);
                if (f.WriteType.Nullable)
                {
                    Methods.AppendLine($"            if (v.{f.Property.Name} is {{ }} x{i}) W{propertyId}(ref tw, x{i});");
                }
                else
                {
                    Methods.AppendLine($"            W{propertyId}(ref tw, v.{f.Property.Name});");
                }

                Methods.AppendLine($"            offsets[{i}] = tw.WrittenCount;");
            }

            Methods.AppendLine("            tw.Flush();");
            Methods.AppendLine($"            w.WriteObjectHeader({fields.Count});");
            Methods.AppendLine($"            for (var i = 0; i < {fields.Count}; i++) w.WriteVarInt(i == 0 ? offsets[0] : offsets[i] - offsets[i - 1]);");
            Methods.AppendLine("            tmp.WriteToAndReset(ref w);");
            Methods.AppendLine("        }");
            Methods.AppendLine("        finally { global::MemoryPack.Internal.ReusableLinkedArrayBufferWriterPool.Return(tmp); }");
            Methods.AppendLine("    }");

            var readable = fields.Where(f => f.Parameter is not null || f.Settable).ToList();
            ReaderSignature(id, display);
            Methods.AppendLine("    {");
            Methods.AppendLine("        Rt.EnterContainer(depth, l);");
            Methods.AppendLine("        if (!r.TryReadObjectHeader(out var count))");
            Methods.AppendLine(type.Nullable && !isStruct ? "            return default;" : "            throw Rt.NullObject();");
            Methods.AppendLine("        global::System.Span<int> d = stackalloc int[count];");
            Methods.AppendLine("        Rt.ReadMemberLengths(ref r, d);");
            foreach (var f in readable)
            {
                Methods.AppendLine($"        {f.ReadType.Display()} {f.Local} = {InitialValue(f)}; var h{f.Local} = false;");
            }

            for (var i = 0; i < fields.Count; i++)
            {
                var f = fields[i];
                Methods.Append($"        if (count > {i} && d[{i}] != 0) {{ var s{i} = r.Consumed; ");
                if (f.Parameter is not null || f.Settable)
                {
                    // A nullable value-type member is written bare (null is a missing member); nullable references accept either form.
                    var readType = f.ReadType.Nullable && f.ReadType.Symbol.IsValueType ? f.ReadType.NonNull : f.ReadType;
                    Methods.Append($"{f.Local} = R{IdOf(readType)}(ref r, l, depth + 1); h{f.Local} = true; ");
                }
                else
                {
                    Methods.Append($"r.Advance(d[{i}]); ");
                }

                Methods.AppendLine($"Rt.EndMember(ref r, s{i}, d[{i}]); }}");
            }

            Methods.AppendLine($"        Rt.SkipExtraMembers(ref r, d, {fields.Count});");
            foreach (var f in readable)
            {
                if (f.ReadType.Nullable || f.ReadType.Symbol.IsValueType) continue;
                if (f.Parameter is { HasExplicitDefaultValue: true }) continue;
                Methods.AppendLine($"        if (!h{f.Local}) throw Rt.MissingField(\"{CborEmitter.Escape(f.Key)}\");");
            }

            var args = string.Join(", ", constructor.Parameters.Select(p => readable.First(f => f.Parameter is not null && SymbolEqualityComparer.Default.Equals(f.Parameter, p)).Local));
            var initializers = readable.Where(f => f.Parameter is null).ToList();
            var tail = initializers.Count == 0 ? "" : " { " + string.Join(", ", initializers.Select(f => $"{f.Property.Name} = {f.Local}")) + " }";
            Methods.AppendLine($"        return new {CborEmitter.Fq(symbol)}({args}){tail};");
            Methods.AppendLine("    }");
            Methods.AppendLine();
        }

        private static string InitialValue(WireField field)
        {
            if (field.Parameter is { HasExplicitDefaultValue: true } p)
            {
                var value = p.ExplicitDefaultValue;
                if (value is null) return "default";
                if (field.ReadType.Kind == WireKind.Enum) return $"({field.ReadType.NonNull.Display()}){Convert.ToString(value, CultureInfo.InvariantCulture)}";
                return Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatPrimitive(value, true, false);
            }

            return field.ReadType.Nullable || field.ReadType.Symbol.IsValueType ? "default" : "default!";
        }
    }
}
