using System.Text;
using Microsoft.CodeAnalysis;

namespace Bazaar.Wire.Generators;

/// <summary>
/// Emits the MessagePack registry and the direct <c>MessagePackWriter</c>/<c>MessagePackReader</c> code for every payload
/// (doc 90 sections 3 and 4.5). The code calls only the low-level reader and writer (no resolver, no typeless mode) and
/// needs no mirror DTOs, because it reads and writes the contract records themselves.
/// </summary>
internal static class MsgPackEmitter
{
    public static string Emit(Compilation compilation, List<PayloadInfo> payloads, List<DiagnosticInfo> diagnostics, System.Threading.CancellationToken ct)
    {
        var context = new EmitContext(diagnostics, ct);
        foreach (var payload in payloads)
        {
            var reference = context.Resolve(payload.Type, NullableAnnotation.NotAnnotated);
            if (reference is not null) context.IdOf(reference);
        }

        context.Drain();

        var fq = CborEmitter.Fq;
        var ns = compilation.AssemblyName is { Length: > 0 } name ? name + ".Generated" : "Generated";
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by Bazaar.Wire.Generators from the [WirePayload] records in Bazaar.Contracts. Do not edit.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine("using MessagePackWriter = global::MessagePack.MessagePackWriter;");
        sb.AppendLine("using MessagePackReader = global::MessagePack.MessagePackReader;");
        sb.AppendLine("using MsgPackLimits = global::Bazaar.Wire.Codec.MessagePack.MsgPackLimits;");
        sb.AppendLine("using Rt = global::Bazaar.Wire.Codec.MessagePack.MsgPackWireRuntime;");
        sb.AppendLine();
        sb.Append("namespace ").Append(ns).AppendLine(";");
        sb.AppendLine();
        sb.AppendLine("/// <summary>The closed set of wire payload types and their MessagePack readers and writers.</summary>");
        sb.AppendLine("internal static partial class WireMsgPackPayloads");
        sb.AppendLine("{");

        sb.AppendLine("    /// <summary>Every registered payload type with the message types it travels under (empty for replies and shared shapes).</summary>");
        sb.AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<(global::System.Type Type, global::System.Collections.Generic.IReadOnlyList<string> MessageTypes)> All { get; } =");
        sb.AppendLine("    [");
        foreach (var payload in payloads)
        {
            var types = string.Join(", ", payload.MessageTypes.Select(t => "\"" + CborEmitter.Escape(t) + "\""));
            sb.Append("        (typeof(").Append(fq(payload.Type)).Append("), new string[] { ").Append(types).AppendLine(" }),");
        }

        sb.AppendLine("    ];");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>True when <typeparamref name=\"T\"/> is a registered wire payload.</summary>");
        sb.AppendLine("    public static bool IsRegistered<T>()");
        sb.AppendLine("    {");
        sb.Append("        return ");
        sb.Append(payloads.Count == 0 ? "false" : string.Join("\n            || ", payloads.Select(p => $"typeof(T) == typeof({fq(p.Type)})")));
        sb.AppendLine(";");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>Writes one payload as one MessagePack item.</summary>");
        sb.AppendLine("    public static void Write<T>(ref MessagePackWriter w, T value)");
        sb.AppendLine("    {");
        foreach (var payload in payloads)
        {
            var id = context.IdOf(new TypeRef(payload.Type, false, WireKind.Record, null));
            sb.AppendLine($"        if (typeof(T) == typeof({fq(payload.Type)})) {{ W{id}(ref w, ({fq(payload.Type)})(object)value!); return; }}");
        }

        sb.AppendLine("        throw new global::System.NotSupportedException(typeof(T).Name + \" is not a registered wire payload.\");");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>Reads one payload from one MessagePack item, enforcing the decode limits.</summary>");
        sb.AppendLine("    public static T Read<T>(ref MessagePackReader r, MsgPackLimits l)");
        sb.AppendLine("    {");
        foreach (var payload in payloads)
        {
            var id = context.IdOf(new TypeRef(payload.Type, false, WireKind.Record, null));
            sb.AppendLine($"        if (typeof(T) == typeof({fq(payload.Type)})) return (T)(object)R{id}(ref r, l)!;");
        }

        sb.AppendLine("        throw new global::System.NotSupportedException(typeof(T).Name + \" is not a registered wire payload.\");");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.Append(context.Methods);
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string Escape(string text) => CborEmitter.Escape(text);

    private sealed class EmitContext
    {
        private readonly List<DiagnosticInfo> _diagnostics;
        private readonly System.Threading.CancellationToken _ct;
        private readonly TypeResolver _resolver;
        private readonly Dictionary<string, int> _ids = new(StringComparer.Ordinal);
        private readonly Queue<(int Id, TypeRef Type)> _queue = new();

        public EmitContext(List<DiagnosticInfo> diagnostics, System.Threading.CancellationToken ct)
        {
            _diagnostics = diagnostics;
            _ct = ct;
            _resolver = new TypeResolver(diagnostics);
        }

        public StringBuilder Methods { get; } = new();

        public TypeRef? Resolve(ITypeSymbol symbol, NullableAnnotation annotation) => _resolver.Resolve(symbol, annotation);

        public int IdOf(TypeRef type)
        {
            var key = type.Display();
            if (_ids.TryGetValue(key, out var id)) return id;
            id = _ids.Count;
            _ids[key] = id;
            _queue.Enqueue((id, type));
            return id;
        }

        public void Drain()
        {
            while (_queue.Count > 0)
            {
                _ct.ThrowIfCancellationRequested();
                var (id, type) = _queue.Dequeue();
                EmitMethods(id, type);
            }
        }

        private void EmitMethods(int id, TypeRef type)
        {
            var display = type.Display();
            Methods.AppendLine($"    // {display}");
            if (type.Nullable)
            {
                var inner = IdOf(type.NonNull);
                var value = type.Symbol.IsValueType ? "v.Value" : "v!";
                Methods.AppendLine($"    private static void W{id}(ref MessagePackWriter w, {display} v)");
                Methods.AppendLine("    {");
                Methods.AppendLine("        if (v is null) { w.WriteNil(); return; }");
                Methods.AppendLine($"        W{inner}(ref w, {value});");
                Methods.AppendLine("    }");
                Methods.AppendLine($"    private static {display} R{id}(ref MessagePackReader r, MsgPackLimits l)");
                Methods.AppendLine("    {");
                Methods.AppendLine("        if (r.TryReadNil()) return default;");
                Methods.AppendLine($"        return R{inner}(ref r, l);");
                Methods.AppendLine("    }");
                Methods.AppendLine();
                return;
            }

            switch (type.Kind)
            {
                case WireKind.String:
                    Simple(id, display, "w.Write(v);", "Rt.ReadText(ref r, l)");
                    break;
                case WireKind.Bool:
                    Simple(id, display, "w.Write(v);", "r.ReadBoolean()");
                    break;
                case WireKind.Byte:
                    Simple(id, display, "w.Write(v);", "Rt.ReadByte(ref r)");
                    break;
                case WireKind.Int32:
                    Simple(id, display, "w.Write(v);", "r.ReadInt32()");
                    break;
                case WireKind.Int64:
                    Simple(id, display, "w.Write(v);", "r.ReadInt64()");
                    break;
                case WireKind.Single:
                    Simple(id, display, "w.Write(v);", "r.ReadSingle()");
                    break;
                case WireKind.Double:
                    Simple(id, display, "w.Write(v);", "r.ReadDouble()");
                    break;
                case WireKind.Decimal:
                    Simple(id, display, "Rt.WriteDecimal(ref w, v);", "Rt.ReadDecimal(ref r, l)");
                    break;
                case WireKind.Guid:
                    Simple(id, display, "w.Write(v.ToString(\"D\"));", "Rt.ReadGuid(ref r, l)");
                    break;
                case WireKind.DateTimeOffset:
                    Simple(id, display, "Rt.WriteDateTimeOffset(ref w, v);", "Rt.ReadDateTimeOffset(ref r, l)");
                    break;
                case WireKind.Float32Array:
                    Simple(id, display, "Rt.WriteFloat32Array(ref w, v);", "Rt.ReadFloat32Array(ref r, l)");
                    break;
                case WireKind.Float32Memory:
                    Simple(id, display, "Rt.WriteFloat32Array(ref w, v.Span);", "new global::System.ReadOnlyMemory<float>(Rt.ReadFloat32Array(ref r, l))");
                    break;
                case WireKind.Enum:
                    EmitEnum(id, display, (INamedTypeSymbol)type.Symbol);
                    break;
                case WireKind.ReadOnlyList:
                case WireKind.List:
                case WireKind.Array:
                    EmitList(id, display, type);
                    break;
                case WireKind.Record:
                    EmitRecord(id, display, (INamedTypeSymbol)type.Symbol);
                    break;
            }
        }

        private void Simple(int id, string display, string write, string read)
        {
            Methods.AppendLine($"    private static void W{id}(ref MessagePackWriter w, {display} v) {{ {write} }}");
            Methods.AppendLine($"    private static {display} R{id}(ref MessagePackReader r, MsgPackLimits l) => {read};");
            Methods.AppendLine();
        }

        private void EmitEnum(int id, string display, INamedTypeSymbol symbol)
        {
            var members = new List<(string Field, string Wire)>();
            string? fallback = null;
            foreach (var field in symbol.GetMembers().OfType<IFieldSymbol>())
            {
                if (!field.IsConst) continue;
                var wire = CborEmitter.Camel(field.Name);
                foreach (var attribute in field.GetAttributes())
                {
                    if (attribute.AttributeClass?.Name == "JsonStringEnumMemberNameAttribute"
                        && attribute.ConstructorArguments.Length == 1
                        && attribute.ConstructorArguments[0].Value is string custom)
                    {
                        wire = custom;
                    }
                }

                members.Add((field.Name, wire));
                if (field.Name == "Unknown" || (field.Name == "Unspecified" && fallback is null)) fallback = field.Name;
            }

            Methods.AppendLine($"    private static void W{id}(ref MessagePackWriter w, {display} v)");
            Methods.AppendLine("    {");
            Methods.AppendLine("        w.Write(v switch");
            Methods.AppendLine("        {");
            foreach (var (field, wire) in members) Methods.AppendLine($"            {display}.{field} => \"{Escape(wire)}\",");
            Methods.AppendLine("            _ => throw new global::System.ArgumentOutOfRangeException(nameof(v)),");
            Methods.AppendLine("        });");
            Methods.AppendLine("    }");
            Methods.AppendLine($"    private static {display} R{id}(ref MessagePackReader r, MsgPackLimits l)");
            Methods.AppendLine("    {");
            Methods.AppendLine("        var s = Rt.ReadText(ref r, l);");
            Methods.AppendLine("        switch (s)");
            Methods.AppendLine("        {");
            foreach (var (field, wire) in members) Methods.AppendLine($"            case \"{Escape(wire)}\": return {display}.{field};");
            Methods.AppendLine(fallback is null
                ? $"            default: throw Rt.UnknownEnum(\"{symbol.Name}\", s);"
                : $"            default: return {display}.{fallback};");
            Methods.AppendLine("        }");
            Methods.AppendLine("    }");
            Methods.AppendLine();
        }

        private void EmitList(int id, string display, TypeRef type)
        {
            var element = type.Element!;
            var elementId = IdOf(element);
            var elementDisplay = element.Display();
            var count = type.Kind == WireKind.Array ? "Length" : "Count";
            Methods.AppendLine($"    private static void W{id}(ref MessagePackWriter w, {display} v)");
            Methods.AppendLine("    {");
            Methods.AppendLine($"        w.WriteArrayHeader(v.{count});");
            Methods.AppendLine($"        for (var i = 0; i < v.{count}; i++) W{elementId}(ref w, v[i]);");
            Methods.AppendLine("    }");
            Methods.AppendLine($"    private static {display} R{id}(ref MessagePackReader r, MsgPackLimits l)");
            Methods.AppendLine("    {");
            Methods.AppendLine("        var count = Rt.ReadArrayStart(ref r, l);");
            Methods.AppendLine($"        var list = new global::System.Collections.Generic.List<{elementDisplay}>(count);");
            Methods.AppendLine($"        for (var i = 0; i < count; i++) list.Add(R{elementId}(ref r, l));");
            Methods.AppendLine("        Rt.Leave(ref r);");
            Methods.AppendLine(type.Kind == WireKind.Array ? "        return list.ToArray();" : "        return list;");
            Methods.AppendLine("    }");
            Methods.AppendLine();
        }

        private void EmitRecord(int id, string display, INamedTypeSymbol symbol)
        {
            var shape = RecordShape.Analyze(symbol, _resolver, _diagnostics);
            if (shape is null) return;
            var fields = shape.Fields;

            Methods.AppendLine($"    private static void W{id}(ref MessagePackWriter w, {display} v)");
            Methods.AppendLine("    {");
            var required = fields.Count(f => !f.WriteType.Nullable);
            Methods.AppendLine($"        var count = {required};");
            foreach (var f in fields.Where(f => f.WriteType.Nullable)) Methods.AppendLine($"        if (v.{f.Property.Name} is not null) count++;");
            Methods.AppendLine("        w.WriteMapHeader(count);");
            foreach (var f in fields)
            {
                var propertyId = IdOf(f.WriteType.NonNull);
                if (f.WriteType.Nullable)
                {
                    Methods.AppendLine($"        if (v.{f.Property.Name} is {{ }} x{f.Local}) {{ w.WriteString(\"{Escape(f.Key)}\"u8); W{propertyId}(ref w, x{f.Local}); }}");
                }
                else
                {
                    Methods.AppendLine($"        w.WriteString(\"{Escape(f.Key)}\"u8); W{propertyId}(ref w, v.{f.Property.Name});");
                }
            }

            Methods.AppendLine("    }");

            var readable = fields.Where(f => f.Parameter is not null || f.Settable).ToList();
            Methods.AppendLine($"    private static {display} R{id}(ref MessagePackReader r, MsgPackLimits l)");
            Methods.AppendLine("    {");
            Methods.AppendLine("        var count = Rt.ReadMapStart(ref r, l);");
            foreach (var f in readable)
            {
                Methods.AppendLine($"        {f.ReadType.Display()} {f.Local} = {RecordShape.InitialValue(f)}; var h{f.Local} = false;");
            }

            Methods.AppendLine("        for (var i = 0; i < count; i++)");
            Methods.AppendLine("        {");
            Methods.AppendLine("            var key = Rt.ReadKey(ref r, l);");
            var first = true;
            foreach (var f in readable)
            {
                var readId = IdOf(f.ReadType);
                Methods.AppendLine($"            {(first ? "if" : "else if")} (global::System.MemoryExtensions.SequenceEqual(key, \"{Escape(f.Key)}\"u8)) {{ if (h{f.Local}) throw Rt.DuplicateKey(\"{Escape(f.Key)}\"); {f.Local} = R{readId}(ref r, l); h{f.Local} = true; }}");
                first = false;
            }

            Methods.AppendLine($"            {(first ? "" : "else ")}Rt.SkipValue(ref r, l);");
            Methods.AppendLine("        }");
            Methods.AppendLine("        Rt.Leave(ref r);");
            foreach (var f in readable)
            {
                if (f.ReadType.Nullable || f.ReadType.Symbol.IsValueType) continue;
                if (f.Parameter is { HasExplicitDefaultValue: true }) continue;
                Methods.AppendLine($"        if (!h{f.Local}) throw Rt.MissingField(\"{Escape(f.Key)}\");");
            }

            Methods.AppendLine($"        return {shape.Construct(display, readable)};");
            Methods.AppendLine("    }");
            Methods.AppendLine();
        }
    }
}
