using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Bazaar.Wire.Generators;

internal enum WireKind
{
    String,
    Bool,
    Byte,
    Int32,
    Int64,
    Single,
    Double,
    Decimal,
    Guid,
    DateTimeOffset,
    Enum,
    Float32Memory,
    Float32Array,
    ReadOnlyList,
    List,
    Array,
    Record,
}

/// <summary>A wire type as the generator sees it: the symbol without nullability, plus whether null is allowed.</summary>
internal sealed class TypeRef
{
    public TypeRef(ITypeSymbol symbol, bool nullable, WireKind kind, TypeRef? element)
    {
        Symbol = symbol;
        Nullable = nullable;
        Kind = kind;
        Element = element;
    }

    public ITypeSymbol Symbol { get; }

    public bool Nullable { get; }

    public WireKind Kind { get; }

    public TypeRef? Element { get; }

    public TypeRef NonNull => Nullable ? new TypeRef(Symbol, false, Kind, Element) : this;

    public string Display()
    {
        var core = Kind switch
        {
            WireKind.ReadOnlyList => $"global::System.Collections.Generic.IReadOnlyList<{Element!.Display()}>",
            WireKind.List => $"global::System.Collections.Generic.List<{Element!.Display()}>",
            WireKind.Array => $"{Element!.Display()}[]",
            _ => Symbol.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
        };
        return Nullable ? core + "?" : core;
    }
}

/// <summary>Emits the CBOR registry and the direct <c>CborWriter</c>/<c>CborReader</c> code for every payload (doc 90 sections 3 and 4.5).</summary>
internal static class CborEmitter
{
    public static string Emit(Compilation compilation, List<PayloadInfo> payloads, List<DiagnosticInfo> diagnostics, System.Threading.CancellationToken ct)
    {
        var context = new EmitContext(diagnostics, ct);
        foreach (var payload in payloads)
        {
            var reference = context.Resolve(payload.Type, NullableAnnotation.NotAnnotated);
            if (reference is not null) context.IdOf(reference);
        }

        context.Drain();

        var ns = compilation.AssemblyName is { Length: > 0 } name ? name + ".Generated" : "Generated";
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by Bazaar.Wire.Generators from the [WirePayload] records in Bazaar.Contracts. Do not edit.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine("using CborWriter = global::System.Formats.Cbor.CborWriter;");
        sb.AppendLine("using CborReader = global::System.Formats.Cbor.CborReader;");
        sb.AppendLine("using CborReaderState = global::System.Formats.Cbor.CborReaderState;");
        sb.AppendLine("using CborLimits = global::Bazaar.Wire.Codec.Cbor.CborLimits;");
        sb.AppendLine("using Rt = global::Bazaar.Wire.Codec.Cbor.CborWireRuntime;");
        sb.AppendLine();
        sb.Append("namespace ").Append(ns).AppendLine(";");
        sb.AppendLine();
        sb.AppendLine("/// <summary>The closed set of wire payload types and their CBOR readers and writers.</summary>");
        sb.AppendLine("internal static partial class WireCborPayloads");
        sb.AppendLine("{");

        sb.AppendLine("    /// <summary>Every registered payload type with the message types it travels under (empty for replies and shared shapes).</summary>");
        sb.AppendLine("    public static global::System.Collections.Generic.IReadOnlyList<(global::System.Type Type, global::System.Collections.Generic.IReadOnlyList<string> MessageTypes)> All { get; } =");
        sb.AppendLine("    [");
        foreach (var payload in payloads)
        {
            var types = string.Join(", ", payload.MessageTypes.Select(t => "\"" + Escape(t) + "\""));
            sb.Append("        (typeof(").Append(Fq(payload.Type)).Append("), new string[] { ").Append(types).AppendLine(" }),");
        }

        sb.AppendLine("    ];");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>True when <typeparamref name=\"T\"/> is a registered wire payload.</summary>");
        sb.AppendLine("    public static bool IsRegistered<T>()");
        sb.AppendLine("    {");
        sb.Append("        return ");
        sb.Append(payloads.Count == 0 ? "false" : string.Join("\n            || ", payloads.Select(p => $"typeof(T) == typeof({Fq(p.Type)})")));
        sb.AppendLine(";");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>Writes one payload as one CBOR data item.</summary>");
        sb.AppendLine("    public static void Write<T>(CborWriter w, T value)");
        sb.AppendLine("    {");
        foreach (var payload in payloads)
        {
            var id = context.IdOf(new TypeRef(payload.Type, false, WireKind.Record, null));
            sb.AppendLine($"        if (typeof(T) == typeof({Fq(payload.Type)})) {{ W{id}(w, ({Fq(payload.Type)})(object)value!); return; }}");
        }

        sb.AppendLine("        throw new global::System.NotSupportedException(typeof(T).Name + \" is not a registered wire payload.\");");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>Reads one payload from one CBOR data item, enforcing the decode limits.</summary>");
        sb.AppendLine("    public static T Read<T>(CborReader r, CborLimits l)");
        sb.AppendLine("    {");
        foreach (var payload in payloads)
        {
            var id = context.IdOf(new TypeRef(payload.Type, false, WireKind.Record, null));
            sb.AppendLine($"        if (typeof(T) == typeof({Fq(payload.Type)})) return (T)(object)R{id}(r, l)!;");
        }

        sb.AppendLine("        throw new global::System.NotSupportedException(typeof(T).Name + \" is not a registered wire payload.\");");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.Append(context.Methods);
        sb.AppendLine("}");
        return sb.ToString();
    }

    internal static string Fq(ITypeSymbol symbol) =>
        symbol.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    internal static string Escape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");

    /// <summary>The same camel-casing System.Text.Json applies, so map keys equal the JSON property names.</summary>
    internal static string Camel(string name)
    {
        if (string.IsNullOrEmpty(name) || !char.IsUpper(name[0])) return name;
        var chars = name.ToCharArray();
        for (var i = 0; i < chars.Length; i++)
        {
            if (i == 1 && !char.IsUpper(chars[i])) break;
            var hasNext = i + 1 < chars.Length;
            if (i > 0 && hasNext && !char.IsUpper(chars[i + 1]))
            {
                if (chars[i + 1] == ' ') chars[i] = char.ToLowerInvariant(chars[i]);
                break;
            }

            chars[i] = char.ToLowerInvariant(chars[i]);
        }

        return new string(chars);
    }

    private sealed class EmitContext
    {
        private readonly List<DiagnosticInfo> _diagnostics;
        private readonly System.Threading.CancellationToken _ct;
        private readonly Dictionary<string, int> _ids = new(StringComparer.Ordinal);
        private readonly Queue<(int Id, TypeRef Type)> _queue = new();

        public EmitContext(List<DiagnosticInfo> diagnostics, System.Threading.CancellationToken ct)
        {
            _diagnostics = diagnostics;
            _ct = ct;
        }

        public StringBuilder Methods { get; } = new();

        public TypeRef? Resolve(ITypeSymbol symbol, NullableAnnotation annotation)
        {
            var nullable = false;
            if (symbol is INamedTypeSymbol { IsValueType: true, OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } wrapper)
            {
                symbol = wrapper.TypeArguments[0];
                nullable = true;
            }
            else if (symbol.IsReferenceType && annotation == NullableAnnotation.Annotated)
            {
                nullable = true;
            }

            switch (symbol.SpecialType)
            {
                case SpecialType.System_String: return new TypeRef(symbol, nullable, WireKind.String, null);
                case SpecialType.System_Boolean: return new TypeRef(symbol, nullable, WireKind.Bool, null);
                case SpecialType.System_Byte: return new TypeRef(symbol, nullable, WireKind.Byte, null);
                case SpecialType.System_Int32: return new TypeRef(symbol, nullable, WireKind.Int32, null);
                case SpecialType.System_Int64: return new TypeRef(symbol, nullable, WireKind.Int64, null);
                case SpecialType.System_Single: return new TypeRef(symbol, nullable, WireKind.Single, null);
                case SpecialType.System_Double: return new TypeRef(symbol, nullable, WireKind.Double, null);
                case SpecialType.System_Decimal: return new TypeRef(symbol, nullable, WireKind.Decimal, null);
                case SpecialType.System_DateTime: return Unsupported(symbol);
            }

            if (symbol.TypeKind == TypeKind.Enum) return new TypeRef(symbol, nullable, WireKind.Enum, null);

            if (symbol is IArrayTypeSymbol array)
            {
                if (array.Rank != 1) return Unsupported(symbol);
                if (array.ElementType.SpecialType == SpecialType.System_Single) return new TypeRef(symbol, nullable, WireKind.Float32Array, null);
                var element = Resolve(array.ElementType, array.ElementNullableAnnotation);
                return element is null ? null : new TypeRef(symbol, nullable, WireKind.Array, element);
            }

            if (symbol is INamedTypeSymbol named)
            {
                var fq = named.OriginalDefinition.ToDisplayString();
                switch (fq)
                {
                    case "System.Guid": return new TypeRef(symbol, nullable, WireKind.Guid, null);
                    case "System.DateTimeOffset": return new TypeRef(symbol, nullable, WireKind.DateTimeOffset, null);
                    case "System.ReadOnlyMemory<T>" when named.TypeArguments[0].SpecialType == SpecialType.System_Single:
                        return new TypeRef(symbol, nullable, WireKind.Float32Memory, null);
                    case "System.Collections.Generic.IReadOnlyList<T>":
                    case "System.Collections.Generic.List<T>":
                        {
                            var element = Resolve(named.TypeArguments[0], named.TypeArgumentNullableAnnotations[0]);
                            if (element is null) return null;
                            return new TypeRef(symbol, nullable, fq.StartsWith("System.Collections.Generic.List", StringComparison.Ordinal) ? WireKind.List : WireKind.ReadOnlyList, element);
                        }
                }

                if (named.TypeParameters.Length == 0 && named.TypeKind is TypeKind.Class or TypeKind.Struct && named.DeclaredAccessibility == Accessibility.Public)
                {
                    return new TypeRef(symbol, nullable, WireKind.Record, null);
                }
            }

            return Unsupported(symbol);
        }

        private TypeRef? Unsupported(ITypeSymbol symbol)
        {
            _diagnostics.Add(new DiagnosticInfo(Descriptors.UnsupportedType, symbol.ToDisplayString()));
            return null;
        }

        public int IdOf(TypeRef type)
        {
            var key = type.Display();
            if (_ids.TryGetValue(key, out var id)) return id;
            id = _ids.Count;
            _ids[key] = id;
            _queue.Enqueue((id, type));
            return id;
        }

        public void Drain()
        {
            while (_queue.Count > 0)
            {
                _ct.ThrowIfCancellationRequested();
                var (id, type) = _queue.Dequeue();
                EmitMethods(id, type);
            }
        }

        private void EmitMethods(int id, TypeRef type)
        {
            var display = type.Display();
            Methods.AppendLine($"    // {display}");
            if (type.Nullable)
            {
                var inner = IdOf(type.NonNull);
                var value = type.Symbol.IsValueType ? "v.Value" : "v!";
                Methods.AppendLine($"    private static void W{id}(CborWriter w, {display} v)");
                Methods.AppendLine("    {");
                Methods.AppendLine("        if (v is null) { w.WriteNull(); return; }");
                Methods.AppendLine($"        W{inner}(w, {value});");
                Methods.AppendLine("    }");
                Methods.AppendLine($"    private static {display} R{id}(CborReader r, CborLimits l)");
                Methods.AppendLine("    {");
                Methods.AppendLine("        if (r.PeekState() == CborReaderState.Null) { r.ReadNull(); return default; }");
                Methods.AppendLine($"        return R{inner}(r, l);");
                Methods.AppendLine("    }");
                Methods.AppendLine();
                return;
            }

            switch (type.Kind)
            {
                case WireKind.String:
                    Simple(id, display, "w.WriteTextString(v);", "Rt.ReadText(r, l)");
                    break;
                case WireKind.Bool:
                    Simple(id, display, "w.WriteBoolean(v);", "r.ReadBoolean()");
                    break;
                case WireKind.Byte:
                    Simple(id, display, "w.WriteUInt32(v);", "Rt.ReadByte(r)");
                    break;
                case WireKind.Int32:
                    Simple(id, display, "w.WriteInt32(v);", "r.ReadInt32()");
                    break;
                case WireKind.Int64:
                    Simple(id, display, "w.WriteInt64(v);", "r.ReadInt64()");
                    break;
                case WireKind.Single:
                    Simple(id, display, "w.WriteSingle(v);", "r.ReadSingle()");
                    break;
                case WireKind.Double:
                    Simple(id, display, "w.WriteDouble(v);", "r.ReadDouble()");
                    break;
                case WireKind.Decimal:
                    Simple(id, display, "w.WriteDecimal(v);", "r.ReadDecimal()");
                    break;
                case WireKind.Guid:
                    Simple(id, display, "w.WriteTextString(v.ToString(\"D\"));", "Rt.ReadGuid(r, l)");
                    break;
                case WireKind.DateTimeOffset:
                    Simple(id, display, "w.WriteDateTimeOffset(v);", "r.ReadDateTimeOffset()");
                    break;
                case WireKind.Float32Array:
                    Simple(id, display, "Rt.WriteFloat32Array(w, v);", "Rt.ReadFloat32Array(r, l)");
                    break;
                case WireKind.Float32Memory:
                    Simple(id, display, "Rt.WriteFloat32Array(w, v.Span);", "new global::System.ReadOnlyMemory<float>(Rt.ReadFloat32Array(r, l))");
                    break;
                case WireKind.Enum:
                    EmitEnum(id, display, (INamedTypeSymbol)type.Symbol);
                    break;
                case WireKind.ReadOnlyList:
                case WireKind.List:
                case WireKind.Array:
                    EmitList(id, display, type);
                    break;
                case WireKind.Record:
                    EmitRecord(id, display, (INamedTypeSymbol)type.Symbol);
                    break;
            }
        }

        private void Simple(int id, string display, string write, string read)
        {
            Methods.AppendLine($"    private static void W{id}(CborWriter w, {display} v) {{ {write} }}");
            Methods.AppendLine($"    private static {display} R{id}(CborReader r, CborLimits l) => {read};");
            Methods.AppendLine();
        }

        private void EmitEnum(int id, string display, INamedTypeSymbol symbol)
        {
            var members = new List<(string Field, string Wire)>();
            string? fallback = null;
            foreach (var field in symbol.GetMembers().OfType<IFieldSymbol>())
            {
                if (!field.IsConst) continue;
                var wire = Camel(field.Name);
                foreach (var attribute in field.GetAttributes())
                {
                    if (attribute.AttributeClass?.Name == "JsonStringEnumMemberNameAttribute"
                        && attribute.ConstructorArguments.Length == 1
                        && attribute.ConstructorArguments[0].Value is string custom)
                    {
                        wire = custom;
                    }
                }

                members.Add((field.Name, wire));
                if (field.Name == "Unknown" || (field.Name == "Unspecified" && fallback is null)) fallback = field.Name;
            }

            Methods.AppendLine($"    private static void W{id}(CborWriter w, {display} v)");
            Methods.AppendLine("    {");
            Methods.AppendLine("        w.WriteTextString(v switch");
            Methods.AppendLine("        {");
            foreach (var (field, wire) in members) Methods.AppendLine($"            {display}.{field} => \"{Escape(wire)}\",");
            Methods.AppendLine("            _ => throw new global::System.ArgumentOutOfRangeException(nameof(v)),");
            Methods.AppendLine("        });");
            Methods.AppendLine("    }");
            Methods.AppendLine($"    private static {display} R{id}(CborReader r, CborLimits l)");
            Methods.AppendLine("    {");
            Methods.AppendLine("        var s = Rt.ReadText(r, l);");
            Methods.AppendLine("        switch (s)");
            Methods.AppendLine("        {");
            foreach (var (field, wire) in members) Methods.AppendLine($"            case \"{Escape(wire)}\": return {display}.{field};");
            Methods.AppendLine(fallback is null
                ? $"            default: throw Rt.UnknownEnum(\"{symbol.Name}\", s);"
                : $"            default: return {display}.{fallback};");
            Methods.AppendLine("        }");
            Methods.AppendLine("    }");
            Methods.AppendLine();
        }

        private void EmitList(int id, string display, TypeRef type)
        {
            var element = type.Element!;
            var elementId = IdOf(element);
            var elementDisplay = element.Display();
            var count = type.Kind == WireKind.Array ? "Length" : "Count";
            Methods.AppendLine($"    private static void W{id}(CborWriter w, {display} v)");
            Methods.AppendLine("    {");
            Methods.AppendLine($"        w.WriteStartArray(v.{count});");
            Methods.AppendLine($"        for (var i = 0; i < v.{count}; i++) W{elementId}(w, v[i]);");
            Methods.AppendLine("        w.WriteEndArray();");
            Methods.AppendLine("    }");
            Methods.AppendLine($"    private static {display} R{id}(CborReader r, CborLimits l)");
            Methods.AppendLine("    {");
            Methods.AppendLine("        Rt.ReadArrayStart(r, l);");
            Methods.AppendLine($"        var list = new global::System.Collections.Generic.List<{elementDisplay}>();");
            Methods.AppendLine("        var items = 0;");
            Methods.AppendLine("        while (Rt.NextItem(r, l, ref items)) list.Add(R" + elementId + "(r, l));");
            Methods.AppendLine(type.Kind == WireKind.Array ? "        return list.ToArray();" : "        return list;");
            Methods.AppendLine("    }");
            Methods.AppendLine();
        }

        private sealed class Field
        {
            public string Key = "";
            public TypeRef WriteType = null!;
            public TypeRef ReadType = null!;
            public IParameterSymbol? Parameter;
            public IPropertySymbol Property = null!;
            public bool Settable;
            public string Local = "";
        }

        private void EmitRecord(int id, string display, INamedTypeSymbol symbol)
        {
            var fields = new List<Field>();
            var keys = new HashSet<string>(StringComparer.Ordinal);
            foreach (var property in symbol.GetMembers().OfType<IPropertySymbol>())
            {
                if (property.IsStatic || property.IsIndexer || property.Name == "EqualityContract") continue;
                if (property.DeclaredAccessibility != Accessibility.Public || property.GetMethod is not { DeclaredAccessibility: Accessibility.Public }) continue;
                if (property.GetAttributes().Any(a => a.AttributeClass?.Name == "JsonIgnoreAttribute")) continue;

                var writeType = Resolve(property.Type, property.NullableAnnotation);
                if (writeType is null) continue;
                var key = Camel(property.Name);
                if (!keys.Add(key)) _diagnostics.Add(new DiagnosticInfo(Descriptors.DuplicateKey, symbol.ToDisplayString()));
                fields.Add(new Field
                {
                    Key = key,
                    WriteType = writeType,
                    ReadType = writeType,
                    Property = property,
                    Settable = property.SetMethod is { DeclaredAccessibility: Accessibility.Public },
                    Local = "f" + fields.Count.ToString(CultureInfo.InvariantCulture),
                });
            }

            IMethodSymbol? constructor = symbol.InstanceConstructors
                .Where(c => c.DeclaredAccessibility == Accessibility.Public
                    && !(c.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(c.Parameters[0].Type, symbol)))
                .OrderByDescending(c => c.Parameters.Length)
                .FirstOrDefault();
            if (constructor is null)
            {
                _diagnostics.Add(new DiagnosticInfo(Descriptors.NoConstructor, symbol.ToDisplayString()));
                return;
            }

            foreach (var parameter in constructor.Parameters)
            {
                var field = fields.FirstOrDefault(f => string.Equals(f.Property.Name, parameter.Name, StringComparison.OrdinalIgnoreCase));
                if (field is null)
                {
                    _diagnostics.Add(new DiagnosticInfo(Descriptors.NoConstructor, symbol.ToDisplayString() + " (parameter " + parameter.Name + ")"));
                    return;
                }

                var readType = Resolve(parameter.Type, parameter.NullableAnnotation);
                if (readType is null) return;
                field.Parameter = parameter;
                field.ReadType = readType;
            }

            Methods.AppendLine($"    private static void W{id}(CborWriter w, {display} v)");
            Methods.AppendLine("    {");
            var required = fields.Count(f => !f.WriteType.Nullable);
            Methods.AppendLine($"        var count = {required};");
            foreach (var f in fields.Where(f => f.WriteType.Nullable)) Methods.AppendLine($"        if (v.{f.Property.Name} is not null) count++;");
            Methods.AppendLine("        w.WriteStartMap(count);");
            foreach (var f in fields)
            {
                var propertyId = IdOf(f.WriteType.NonNull);
                if (f.WriteType.Nullable)
                {
                    Methods.AppendLine($"        if (v.{f.Property.Name} is {{ }} x{f.Local}) {{ w.WriteTextString(\"{Escape(f.Key)}\"); W{propertyId}(w, x{f.Local}); }}");
                }
                else
                {
                    Methods.AppendLine($"        w.WriteTextString(\"{Escape(f.Key)}\"); W{propertyId}(w, v.{f.Property.Name});");
                }
            }

            Methods.AppendLine("        w.WriteEndMap();");
            Methods.AppendLine("    }");

            var readable = fields.Where(f => f.Parameter is not null || f.Settable).ToList();
            Methods.AppendLine($"    private static {display} R{id}(CborReader r, CborLimits l)");
            Methods.AppendLine("    {");
            Methods.AppendLine("        Rt.ReadMapStart(r, l);");
            foreach (var f in readable)
            {
                var localType = f.ReadType.Display();
                var initial = InitialValue(f);
                Methods.AppendLine($"        {localType} {f.Local} = {initial}; var h{f.Local} = false;");
            }

            Methods.AppendLine("        var items = 0;");
            Methods.AppendLine("        while (Rt.NextKey(r, l, ref items, out var key))");
            Methods.AppendLine("        {");
            Methods.AppendLine("            switch (key)");
            Methods.AppendLine("            {");
            foreach (var f in readable)
            {
                var readId = IdOf(f.ReadType);
                Methods.AppendLine($"                case \"{Escape(f.Key)}\": {f.Local} = R{readId}(r, l); h{f.Local} = true; break;");
            }

            Methods.AppendLine("                default: Rt.SkipValue(r, l); break;");
            Methods.AppendLine("            }");
            Methods.AppendLine("        }");
            foreach (var f in readable)
            {
                if (f.ReadType.Nullable || f.ReadType.Symbol.IsValueType) continue;
                if (f.Parameter is { HasExplicitDefaultValue: true }) continue;
                Methods.AppendLine($"        if (!h{f.Local}) throw Rt.MissingField(\"{Escape(f.Key)}\");");
            }

            var args = string.Join(", ", constructor.Parameters.Select(p => readable.First(f => f.Parameter is not null && SymbolEqualityComparer.Default.Equals(f.Parameter, p)).Local));
            var initializers = readable.Where(f => f.Parameter is null).ToList();
            var tail = initializers.Count == 0 ? "" : " { " + string.Join(", ", initializers.Select(f => $"{f.Property.Name} = {f.Local}")) + " }";
            Methods.AppendLine($"        return new {display}({args}){tail};");
            Methods.AppendLine("    }");
            Methods.AppendLine();
        }

        private static string InitialValue(Field field)
        {
            if (field.Parameter is { HasExplicitDefaultValue: true } p)
            {
                var value = p.ExplicitDefaultValue;
                if (value is null) return "default";
                if (field.ReadType.Kind == WireKind.Enum) return $"({field.ReadType.NonNull.Display()}){Convert.ToString(value, CultureInfo.InvariantCulture)}";
                return SymbolDisplay.FormatPrimitive(value, true, false);
            }

            return field.ReadType.Nullable || field.ReadType.Symbol.IsValueType ? "default" : "default!";
        }
    }
