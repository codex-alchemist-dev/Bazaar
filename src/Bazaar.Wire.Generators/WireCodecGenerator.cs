using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Bazaar.Wire.Generators;

/// <summary>
/// Reads every <c>[WirePayload]</c> record in the referenced <c>Bazaar.Contracts</c> assembly and, for a project that opts in with
/// <c>[assembly: GenerateWireCodec("cbor")]</c> or <c>"msgpack"</c>, emits a closed registry of payload types plus direct reader and writer code
/// (doc 90 section 3). No reflection, no runtime type discovery: the output is plain C# that is trim and AOT safe.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class WireCodecGenerator : IIncrementalGenerator
{
    internal const string PayloadAttributeMetadataName = "Bazaar.Contracts.Wire.WirePayloadAttribute";

    private const string _targetAttributeSource = """
    internal const string TargetAttributeSource = """
        // <auto-generated/>
        #nullable enable
        namespace Bazaar.Wire.Generators
        {
            /// <summary>Opts an assembly in to generated wire codec code (doc 90). Codec names built so far: "cbor", "msgpack", "protobuf" and "schema" (the published schema artifacts, doc 90 section 5).</summary>
            /// <summary>Opts an assembly in to generated wire codec code (doc 90). Codec names built so far: "cbor", "msgpack", "memorypack", "protobuf" and "schema" (the published schema artifacts, doc 90 section 5).</summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Assembly, AllowMultiple = true)]
            internal sealed class GenerateWireCodecAttribute : global::System.Attribute
            {
                public GenerateWireCodecAttribute(string codec) { Codec = codec; }

                public string Codec { get; }
            }
        }
        """;

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(c => c.AddSource("GenerateWireCodecAttribute.g.cs", SourceText.From(_targetAttributeSource, System.Text.Encoding.UTF8)));
        context.RegisterPostInitializationOutput(c => c.AddSource("GenerateWireCodecAttribute.g.cs", SourceText.From(TargetAttributeSource, System.Text.Encoding.UTF8)));

        var locks = context.AdditionalTextsProvider
            .Where(static t => string.Equals(System.IO.Path.GetFileName(t.Path), "schema.lock.json", StringComparison.OrdinalIgnoreCase))
            .Select(static (t, ct) => t.GetText(ct)?.ToString())
            .Collect();
        var generated = context.CompilationProvider.Combine(locks).Select(static (pair, ct) => Run(pair.Left, pair.Right.FirstOrDefault(), ct));
        context.RegisterSourceOutput(generated, static (spc, result) =>
        {
            foreach (var diagnostic in result.Diagnostics) spc.ReportDiagnostic(diagnostic.ToDiagnostic());
            foreach (var file in result.Files) spc.AddSource(file.HintName, SourceText.From(file.Source, System.Text.Encoding.UTF8));
        });
    }

    private static GeneratorResult Run(Compilation compilation, string? lockText, System.Threading.CancellationToken ct)
    {
        var codecs = new List<string>();
        foreach (var attribute in compilation.Assembly.GetAttributes())
        {
            if (attribute.AttributeClass is { Name: "GenerateWireCodecAttribute" } cls
                && cls.ContainingNamespace.ToDisplayString() == "Bazaar.Wire.Generators"
                && attribute.ConstructorArguments.Length == 1
                && attribute.ConstructorArguments[0].Value is string name)
            {
                codecs.Add(name);
            }
        }

        if (codecs.Count == 0) return GeneratorResult.Empty;

        var diagnostics = new List<DiagnosticInfo>();
        var payloads = PayloadModel.Discover(compilation, diagnostics, ct);
        var files = new List<GeneratedFile>();
        foreach (var codec in codecs)
        {
            if (codec == "cbor")
            {
                files.Add(new GeneratedFile("WireCbor.g.cs", CborEmitter.Emit(compilation, payloads, diagnostics, ct)));
            }
            else if (codec == "msgpack")
            {
                files.Add(new GeneratedFile("WireMsgPack.g.cs", MsgPackEmitter.Emit(compilation, payloads, diagnostics, ct)));
            }
            else if (codec == "schema")
            {
                files.Add(new GeneratedFile("WireSchema.g.cs", SchemaOutput.Emit(compilation, payloads, codecs.Contains("cbor"), lockText, diagnostics, ct)));
            }
            else if (codec == "protobuf")
            {
                var (_, source) = ProtobufEmitter.Emit(compilation, payloads, diagnostics, ct);
                files.Add(new GeneratedFile("WireProtobuf.g.cs", source));
            }
            else if (codec == "memorypack")
            {
                files.Add(new GeneratedFile("WireMemoryPack.g.cs", MemoryPackEmitter.Emit(compilation, payloads, diagnostics, ct)));
            }
            else
            {
                diagnostics.Add(new DiagnosticInfo(Descriptors.UnknownCodec, $"'{codec}'"));
            }
        }

        return new GeneratorResult(files.ToImmutableArray(), diagnostics.ToImmutableArray());
    }
}

internal sealed class GeneratedFile
{
    public GeneratedFile(string hintName, string source)
    {
        HintName = hintName;
        Source = source;
    }

    public string HintName { get; }

    public string Source { get; }
}

internal sealed class GeneratorResult : IEquatable<GeneratorResult>
{
    public static readonly GeneratorResult Empty = new(ImmutableArray<GeneratedFile>.Empty, ImmutableArray<DiagnosticInfo>.Empty);

    public GeneratorResult(ImmutableArray<GeneratedFile> files, ImmutableArray<DiagnosticInfo> diagnostics)
    {
        Files = files;
        Diagnostics = diagnostics;
    }

    public ImmutableArray<GeneratedFile> Files { get; }

    public ImmutableArray<DiagnosticInfo> Diagnostics { get; }

    public bool Equals(GeneratorResult? other) =>
        other is not null
        && Files.Length == other.Files.Length
        && Diagnostics.Length == other.Diagnostics.Length
        && Files.Zip(other.Files, (a, b) => a.HintName == b.HintName && a.Source == b.Source).All(x => x)
        && Diagnostics.Zip(other.Diagnostics, (a, b) => a.Equals(b)).All(x => x);

    public override bool Equals(object? obj) => Equals(obj as GeneratorResult);

    public override int GetHashCode() => Files.Length * 31 + Diagnostics.Length;
}

internal sealed class DiagnosticInfo : IEquatable<DiagnosticInfo>
{
    public DiagnosticInfo(DiagnosticDescriptor descriptor, string argument)
    {
        Descriptor = descriptor;
        Argument = argument;
    }

    public DiagnosticDescriptor Descriptor { get; }

    public string Argument { get; }

    public Diagnostic ToDiagnostic() => Diagnostic.Create(Descriptor, Location.None, Argument);

    public bool Equals(DiagnosticInfo? other) => other is not null && Descriptor.Id == other.Descriptor.Id && Argument == other.Argument;

    public override bool Equals(object? obj) => Equals(obj as DiagnosticInfo);

    public override int GetHashCode() => Descriptor.Id.GetHashCode() ^ Argument.GetHashCode();
}

