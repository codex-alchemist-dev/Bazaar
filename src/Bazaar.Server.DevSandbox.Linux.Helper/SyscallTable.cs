    internal static bool IsKnown(string name) => _numbers.ContainsKey(name);

    /// <summary>Gets the number of <paramref name="name"/> on <paramref name="arch"/>; false if the name is unknown or absent there.</summary>
    internal static bool TryGetNumber(string name, SeccompArch arch, out int number)
    {
        number = -1;
        if (!_numbers.TryGetValue(name, out var pair))
        {
            return false;
        }

        number = arch == SeccompArch.X64 ? pair.X64 : pair.Arm64;
        return number >= 0;
    }
